"""M2e-F: throughput of the champion-mode environment (single process), by agent pair and with the bounded
lane-step cache, against the legacy siege model through the same environment."""

from __future__ import annotations

import platform
import time

import numpy as np

from ...config import GameConfig
from ...env import LaneEnv, ScriptedAgent, champion_agents, run_episodes
from ...baselines import aggressive, passive_safe
from .common import md_table, write


def _time_steps(cfg, episodes: int, seed: int, cache: int = 0) -> float:
    """Raw env.step throughput with uniformly random legal actions (no agent logic), turns per second."""
    env = LaneEnv(cfg, cache_size=cache)
    rng = np.random.default_rng(seed)
    turns = 0
    t0 = time.perf_counter()
    for e in range(episodes):
        oa, ob = env.reset(seed=seed + e)
        while True:
            r = env.step(oa.legal[rng.integers(len(oa.legal))], ob.legal[rng.integers(len(ob.legal))])
            turns += 1
            if r.done:
                break
            oa, ob = r.obs
    return turns / (time.perf_counter() - t0)


def run(episodes: int = 300, seed: int = 5):
    cfg = GameConfig.champions()
    agents = champion_agents(cfg)
    rows, out = [], {}
    for na, nb in (("hold_farmer", "aggressive_trader"), ("opportunistic_trader", "punisher"), ("uniform", "uniform"),
                   ("shover", "yield_farmer")):
        for cache in (0, 20000):
            st = run_episodes(LaneEnv(cfg, cache_size=cache), agents[na], agents[nb], episodes, seed)
            out[f"{na} vs {nb} cache {cache}"] = {"turns_per_second": st.turns_per_second,
                                                  "episodes_per_second": st.episodes_per_second}
            rows.append([f"champion: {na} vs {nb}", cache, f"{st.turns_per_second:,.0f}", f"{st.episodes_per_second:,.0f}"])
    for cache in (0, 20000):
        tps = _time_steps(cfg, episodes, seed, cache)
        out[f"raw step champion cache {cache}"] = {"turns_per_second": tps}
        rows.append(["champion: env.step only, random legal actions", cache, f"{tps:,.0f}", f"{tps / cfg.horizon:,.0f}"])
    legacy = GameConfig()
    st = run_episodes(LaneEnv(legacy), ScriptedAgent(aggressive()), ScriptedAgent(passive_safe()), episodes, seed)
    out["legacy siege aggressive vs passive_safe"] = {"turns_per_second": st.turns_per_second}
    rows.append(["legacy siege model: aggressive vs passive_safe", 0, f"{st.turns_per_second:,.0f}",
                 f"{st.episodes_per_second:,.0f}"])
    md = "\n".join([
        "# Champion mode: environment throughput (M2e-F)", "",
        f"Generated by `python -m lanegame experiments-champions benchmark`; {episodes} episodes of K = 32 per row, "
        f"single process, Python {platform.python_version()} on {platform.machine()}. Champion-mode turns include "
        "the lane probe, the authoritative lane step, trades, ganks, death bookkeeping, both observations and "
        "masks, and the full `info` record. Agent rows include the scripted agents' own decision time.", "",
        md_table(["configuration / agents", "lane cache entries", "turns per second", "episodes per second"], rows), ""])
    write("benchmark", out, md)
    return out


if __name__ == "__main__":
    run()
