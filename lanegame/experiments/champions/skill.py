"""M2e-C: mechanical-skill sweeps. Skill must improve execution (realized hit rate, damage per connected trade,
damage taken per gank) monotonically, and must not by itself change what a fixed policy does (positions,
behaviors); whether it raises the final payoff depends on the matchup."""

from __future__ import annotations

import numpy as np

from .common import base_config, fmt_ci, md_table, run_pairs, write

SKILLS = [(0.5, 0.5), (0.65, 0.35), (0.8, 0.2), (1.0, 0.0), (0.35, 0.65), (0.2, 0.8)]
PAIRS = [("aggressive_trader", "aggressive_trader"), ("aggressive_trader", "hold_farmer"),
         ("hold_farmer", "aggressive_trader"), ("opportunistic_trader", "hold_farmer"), ("hold_farmer", "hold_farmer"),
         ("aggressive_trader", "yield_farmer")]


def _rate(num, den):
    return float(num) / float(den) if den > 0 else float("nan")


def run(episodes: int = 400, seed: int = 13):
    rows, data = [], []
    for sa, sb in SKILLS:
        cfg = base_config(skill_a=sa, skill_b=sb)
        recs = run_pairs(cfg, PAIRS, episodes, seed)
        for (na, nb), r in zip(PAIRS, recs):
            hit = [_rate(r["trades_landed"][s], r["trades_connected"][s]) for s in (0, 1)]
            dmg = [_rate(r["trade_damage_dealt"][s], r["trades_connected"][s]) for s in (0, 1)]
            gank = [_rate(r["gank_damage_taken"][s], r["ganks"][s]) for s in (0, 1)]
            data.append({"skill": [sa, sb], "pair": [na, nb], "record": r, "hit_rate": hit,
                         "damage_per_connected_trade": dmg, "damage_per_gank": gank})
            f = lambda x: "-" if np.isnan(x) else f"{x:.2f}"
            rows.append([f"{sa:.2f} / {sb:.2f}", f"{na} vs {nb}", fmt_ci(r["mean"], r["stderr"]),
                         f"{f(hit[0])} / {f(hit[1])}", f"{f(dmg[0])} / {f(dmg[1])}", f"{f(gank[0])} / {f(gank[1])}",
                         f"{r['deaths'][0]:.2f} / {r['deaths'][1]:.2f}", f"{r['farm'][0]:.2f} / {r['farm'][1]:.2f}",
                         f"{r['trades_connected'][0]:.1f} / {r['trades_connected'][1]:.1f}"])
    # monotonicity of execution in A's skill advantage (equal-skill and A-favoured rows, same pair)
    checks = []
    adv = [(0.5, 0.5), (0.65, 0.35), (0.8, 0.2), (1.0, 0.0)]
    for pair in PAIRS:
        seq = [d for s in adv for d in data if d["skill"] == list(s) and d["pair"] == list(pair)]
        h = [d["hit_rate"][0] for d in seq]
        g = [d["damage_per_gank"][0] for d in seq]
        if not any(np.isnan(h)):
            checks.append({"pair": list(pair), "quantity": "A's realized hit rate", "values": h,
                           "monotone": bool(all(np.diff(h) > -0.02))})
        if not any(np.isnan(g)):
            checks.append({"pair": list(pair), "quantity": "A's damage per gank", "values": g,
                           "monotone": bool(all(np.diff(g) < 0.05))})
    crows = [[" vs ".join(c["pair"]), c["quantity"], " -> ".join(f"{v:.3f}" for v in c["values"]),
              "yes" if c["monotone"] else "NO"] for c in checks]
    md = "\n".join([
        "# Champion mode: mechanical-skill sweeps (M2e-C)", "",
        f"Generated by `python -m lanegame experiments-champions skill`; {episodes} episodes per cell, seed {seed} "
        "(common random numbers across cells), K = 32. Skill (A / B) is a property of the seat; the agent named first "
        "plays seat A. Payoff to A with a 95% confidence interval. Hit rate = landed / connected trades; damage per "
        "connected trade and per gank are realized averages.", "",
        md_table(["skill A / B", "matchup", "payoff to A", "hit rate A / B", "dmg per connected trade A / B",
                  "dmg per gank A / B", "deaths A / B", "farm A / B", "connected trades A / B"], rows), "",
        "Execution monotonicity in A's skill advantage (0.5/0.5 -> 0.65/0.35 -> 0.8/0.2 -> 1.0/0.0; sampling "
        "tolerance 0.02 for hit rates, 0.05 HP for gank damage):", "",
        md_table(["matchup", "quantity", "values", "monotone"], crows), ""])
    write("skill", {"cells": data, "checks": checks, "episodes": episodes, "seed": seed}, md)
    return data, checks


if __name__ == "__main__":
    run()
