"""M2e-B: behavioral validity. Round robin of the scripted champion agents (both seats, common random numbers),
per-agent economic and combat statistics, and the zero-sum Nash equilibrium of the empirical payoff matrix
(which constant or simple scripted strategy, if any, dominates)."""

from __future__ import annotations

import numpy as np

from .common import base_config, fmt_ci, md_table, meta_nash, round_robin, write

SUITE = ["hold_farmer", "yield_farmer", "aggressive_trader", "safe_player", "shover", "conservative_recaller",
         "opportunistic_trader", "vision_player", "punisher"]
NAIVE = ["hold", "trade", "yield", "safe", "uniform"]
SHORT = {"hold_farmer": "hold_f", "yield_farmer": "yield_f", "aggressive_trader": "aggr_tr", "safe_player": "safe_p",
         "conservative_recaller": "cons_rec", "opportunistic_trader": "opp_tr", "vision_player": "vision_sh",
         "hold": "HOLD", "trade": "TRADE", "yield": "YIELD", "safe": "SAFE"}
METRICS = ["farm", "plates", "trade_damage_dealt", "damage_taken", "gank_damage_taken", "deaths", "recalls",
           "recalls_interrupted", "turns_away", "ganks", "exposure", "trades_connected", "trades_landed",
           "tower_damage_taken"]


def per_agent(rr: dict) -> dict:
    """Mean of each metric for each agent over all its games (both seats)."""
    names = rr["names"]
    out = {n: {m: [] for m in METRICS} for n in names}
    for n in names:
        out[n]["behaviors"] = {}
        out[n]["objectives"] = {"Pressure": [], "Vision": []}
    for r in rr["pairs"]:
        for s, n in enumerate(r["names"]):
            for m in METRICS:
                out[n][m].append(r[m][s])
            for k, v in r["behaviors"][s].items():
                out[n]["behaviors"].setdefault(k, []).append(v)
            for k, v in r["objectives"][s].items():
                out[n]["objectives"][k].append(v)
    for n in names:
        for m in METRICS:
            out[n][m] = float(np.mean(out[n][m]))
        g = len(rr["pairs"]) * 2 / len(names)
        out[n]["behaviors"] = {k: float(np.sum(v) / g) for k, v in out[n]["behaviors"].items()}
        out[n]["objectives"] = {k: float(np.sum(v) / g) for k, v in out[n]["objectives"].items()}
    return out


def tournament_markdown(rr: dict, nash: dict, stats: dict, title: str, note: str) -> str:
    names = rr["names"]
    M, SE = np.array(rr["matrix"]), np.array(rr["stderr"])
    avg = M.mean(axis=1)
    order = list(np.argsort(-avg))
    short = {n: SHORT.get(n, n) for n in names}
    rows = [[short[names[i]], f"{avg[i]:+.2f}"] + [f"{M[i, j]:+.2f}" for j in order] for i in order]
    lines = [f"# {title}", "", note, "",
             "Payoff matrix: mean resources of the ROW agent per 32-turn game against the COLUMN agent, averaged over "
             "both seats; rows sorted by their average. Half-width of the 95% confidence interval: at most "
             f"{1.96 * SE.max():.2f} (median {1.96 * np.median(SE):.2f}).", "",
             md_table(["row \\ column", "average"] + [short[names[j]] for j in order], rows), "",
             f"Zero-sum Nash equilibrium of this empirical matrix (value {nash['value']:+.3f}): "
             + ", ".join(f"{k} {v:.2f}" for k, v in sorted(nash["mixture"].items(), key=lambda kv: -kv[1])) + ".", "",
             "Per-agent averages over all its games (both seats):", ""]
    hdr = ["agent", "farm", "plates", "trade dmg dealt", "HP lost", "to ganks", "deaths", "recalls", "interrupted",
           "turns away", "ganks", "exposure", "behaviors"]
    rows = []
    for i in order:
        n = names[i]
        st = stats[n]
        beh = " ".join(f"{k} {v:.2f}" for k, v in st["behaviors"].items() if v >= 0.005)
        rows.append([short[n], f"{st['farm']:.2f}", f"{st['plates']:.2f}", f"{st['trade_damage_dealt']:.2f}",
                     f"{st['damage_taken']:.2f}", f"{st['gank_damage_taken']:.2f}", f"{st['deaths']:.2f}",
                     f"{st['recalls']:.2f}", f"{st['recalls_interrupted']:.2f}", f"{st['turns_away']:.2f}",
                     f"{st['ganks']:.2f}", f"{st['exposure']:+.2f}", beh])
    lines += [md_table(hdr, rows), ""]
    return "\n".join(lines)


def run(episodes: int = 400, seed: int = 7):
    cfg = base_config()
    names = SUITE + NAIVE
    rr = round_robin(cfg, names, episodes, seed)
    nash = meta_nash(np.array(rr["matrix"]), names)
    stats = per_agent(rr)
    nash_suite = meta_nash(np.array(rr["matrix"])[:len(SUITE), :len(SUITE)], SUITE)
    note = (f"Generated by `python -m lanegame experiments-champions tournament`: `GameConfig.champions()` (K = 32, "
            f"equal skill 0.5), {episodes} episodes per ordered pair with the same seed for every pair (common random "
            f"numbers), {len(names) ** 2} ordered pairs, {rr['elapsed_s']:.0f} s. Agents: the scripted suite "
            "(`lanegame.env.agents.champion_suite`, each recalls at <= 2 HP unless noted; short names: "
            "hold_f = hold_farmer, yield_f = yield_farmer, aggr_tr = aggressive_trader (recalls at 1 HP), safe_p = "
            "safe_player, shover, cons_rec = conservative_recaller (recalls at 4 HP), opp_tr = opportunistic_trader, "
            "vision_sh = vision_player (shoves, Vision when sieging), punisher) and naive constant behaviors that "
            "never recall (upper case: HOLD, TRADE, YIELD, SAFE) plus uniform random play.")
    md = tournament_markdown(rr, nash, stats, "Champion mode: scripted round robin (M2e-B)", note)
    md += (f"\nRestricted to the {len(SUITE)} suite agents, the equilibrium is (value {nash_suite['value']:+.3f}): "
           + ", ".join(f"{k} {v:.2f}" for k, v in sorted(nash_suite["mixture"].items(), key=lambda kv: -kv[1])) + ".\n")
    write("tournament", {"round_robin": rr, "nash": nash, "nash_suite": nash_suite, "per_agent": stats,
                         "episodes": episodes, "seed": seed, "config": cfg.to_dict()}, md)
    return rr, nash, stats


if __name__ == "__main__":
    run()
