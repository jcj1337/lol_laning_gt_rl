"""When do the strongest Phase D attackers shove and siege? (docs/rl/openai_five_diagnostics_report.md, section D)

Audits each final 1,024k attacker against its own frozen target (lanegame.diagnostics.audit_games, 100 held-out
episodes per seat, SeedSequence(52,010)) and reports the attacker's Shove and Pressure probabilities conditioned on
the situation: enemy champion away or present, enemy HP, own HP, turn, own siege. Compare with the rule overlays of
the `overlay` stage, which apply the same actions unconditionally and lose.

    python -m lanegame.experiments.rl.attacker_behavior
"""

from __future__ import annotations

import os
import time
from concurrent.futures import ProcessPoolExecutor

import numpy as np

from ...config import GameConfig
from .common import md_table
from .diagnostics import _load, _write
from .robustness import BR_STEPS, attackers, checkpoint_path

ROOT, EPISODES = 52_010, 100


def _job(args):
    aid, att_path, target_path = args
    import torch
    from ...diagnostics import audit_games
    from ...rl import load_agent
    torch.set_num_threads(1)
    cfg = GameConfig.champions()
    T = audit_games(cfg, load_agent(att_path), load_agent(target_path), EPISODES, ROOT)
    p = T.where(T["present"])
    games = 2 * EPISODES

    def cond(mask):
        q = p.where(mask)
        return {"share": float(mask.mean()), "p_SH": float(q["p_SH"].mean()) if len(q) else float("nan"),
                "p_Trade": float(q["p_Trade"].mean()) if len(q) else float("nan")}
    away = p["eabsent"] > 0
    out = {"payoff": float(T["reward"].sum() / games), "plates": float(T["plates"].sum() / games),
           "crashes": float(T["crash"].sum() / games), "deaths": float(T["died"].sum() / games),
           "edeaths": float(T["edied"].sum() / games),
           "objective_legal_per_game": float(p["legal_objective"].sum() / games),
           "p_pressure_when_legal": float(p["p_obj_Pressure"][p["legal_objective"]].mean())
           if p["legal_objective"].any() else float("nan"),
           "enemy_away": cond(away), "enemy_present": cond(~away),
           "enemy_hp_le2": cond(~away & (p["ehp"] <= 2)), "enemy_hp_ge5": cond(~away & (p["ehp"] >= 5)),
           "own_hp_le2": cond(p["hp"] <= 2), "early_k_lt8": cond(p["k"] < 8), "late_k_ge24": cond(p["k"] >= 24),
           "own_siege": cond(p["siege"] > 0)}
    return aid, out


def run(workers: int = 6):
    t0 = time.perf_counter()
    rob = _load("robustness")["targets"]
    jobs = [(aid, checkpoint_path(aid, BR_STEPS), path) for aid, name, path, mode, seed in attackers()]
    with ProcessPoolExecutor(max_workers=workers) as ex:
        res = dict(ex.map(_job, jobs))
    data = {"root": ROOT, "episodes": EPISODES, "elapsed_s": time.perf_counter() - t0, "results": res}
    _write("attacker_behavior", data, _md)


def _md(data: dict) -> str:
    R = data["results"]
    rows = []
    for aid, v in sorted(R.items(), key=lambda kv: -kv[1]["payoff"]):
        rows.append([aid, f"{v['payoff']:+.2f}", f"{v['plates']:.2f}", f"{v['crashes']:.2f}",
                     f"{v['deaths']:.2f} / {v['edeaths']:.2f}", f"{v['objective_legal_per_game']:.1f}",
                     "" if np.isnan(v["p_pressure_when_legal"]) else f"{v['p_pressure_when_legal']:.2f}"] +
                    [f"{v[c]['p_SH']:.2f}" if not np.isnan(v[c]["p_SH"]) else "" for c in
                     ("enemy_away", "enemy_present", "enemy_hp_le2", "enemy_hp_ge5", "own_hp_le2", "early_k_lt8",
                      "late_k_ge24", "own_siege")])
    return "\n".join(["# Where the Phase D attackers shove and siege", "",
                      f"Generated by `python -m lanegame.experiments.rl.attacker_behavior` "
                      f"({data['elapsed_s'] / 60:.1f} min). Each final attacker against its own target, "
                      f"{data['episodes']} episodes per seat, SeedSequence({data['root']}). Payoff, plates, crashes and "
                      "deaths per game (attacker / target); then the attacker's mean probability of Shove in each "
                      "situation (present turns).", "",
                      md_table(["attacker", "payoff", "plates", "crashes", "deaths own / target",
                                "objective-legal turns", "P(Pressure) given legal", "Shove given enemy away",
                                "Shove given enemy present", "Shove given enemy HP <= 2", "Shove given enemy HP >= 5",
                                "Shove given own HP <= 2", "Shove given turn < 8", "Shove given turn >= 24",
                                "Shove given own siege"], rows), ""])


if __name__ == "__main__":
    run()
