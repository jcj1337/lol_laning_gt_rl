"""M3c addendum: warm-started approximate best responses.

The from-scratch PPO responses of `evaluation` could not even reach parity against some targets (-0.5), which
leaves open whether those targets are robust or the attacker is merely slow. Here each response starts from a
copy of the TARGET's own network (payoff 0 at the start, by symmetry) and is trained against the frozen target
for the same budget; its held-out payoff is then a lower bound on the target's exploitability that is >= 0 up to
noise. Both bounds are reported; the larger is the best available estimate. Neither is a certificate.
"""

from __future__ import annotations

import os
import time
from concurrent.futures import ProcessPoolExecutor

import numpy as np

from ...config import GameConfig
from .common import CKPT, ci, md_table, write

SEEDS = [0, 1, 2]
EVAL_SEED = 30_001


def _targets():
    out = {}
    for s in SEEDS:
        out[f"mix_s{s}"] = os.path.join(CKPT, f"m3a_mixture_s{s}", "final.pt")
        out[f"sp_s{s}"] = os.path.join(CKPT, f"m3b_equal_s{s}", "final.pt")
        out[f"sprand_s{s}"] = os.path.join(CKPT, f"m3b_skillrand_s{s}", "final.pt")
    return out


def _job(args):
    name, path, seed, steps, eval_eps = args
    import torch
    from ...rl import PPOConfig, approximate_best_response, load_agent, load_checkpoint
    torch.set_num_threads(1)
    cfg = GameConfig.champions()
    target = load_agent(path, name=name)
    init = load_checkpoint(path)[0]
    r = approximate_best_response(cfg, target, PPOConfig(total_steps=steps, seed=700 + seed), eval_episodes=eval_eps,
                                  eval_seed=EVAL_SEED, name=f"brwarm_{name}_s{seed}", init_net=init)
    r.pop("agent")
    r["eval"] = {k: r["eval"][k] for k in ("mean", "stderr", "ci95", "win_rate", "x_stats")}
    return (name, seed), r


def run(steps: int = 102_400, eval_eps: int = 500, workers: int = 10):
    import json
    t0 = time.perf_counter()
    targets = _targets()
    jobs = [(n, p, s, steps, eval_eps) for n, p in targets.items() for s in (0, 1)]
    with ProcessPoolExecutor(max_workers=workers) as ex:
        res = dict(ex.map(_job, jobs))
    elapsed = time.perf_counter() - t0
    scratch = {}
    path = os.path.join("results", "rl", "m3c_evaluation.json")
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            scratch = json.load(f).get("br_summary", {})
    rows, summary = [], {}
    for n in targets:
        vals = [res[(n, s)] for s in (0, 1)]
        best = max(v["value"] for v in vals)
        sc = scratch.get(n, {})
        sc_best = max(sc.get("br_values", [float("nan")]))
        summary[n] = {"warm_values": [v["value"] for v in vals], "warm_stderr": [v["stderr"] for v in vals],
                      "scratch_best": sc_best, "curves": [v["curve"] for v in vals]}
        rows.append([n, ", ".join(ci(v["value"], v["stderr"]) for v in vals), f"{best:+.2f}",
                     "-" if np.isnan(sc_best) else f"{sc_best:+.2f}",
                     f"{np.nanmax([best, sc_best]):+.2f}"])
    fam = []
    for f in ("mix", "sp", "sprand"):
        b = [max(summary[f"{f}_s{s}"]["warm_values"]) for s in SEEDS]
        fam.append([f, ", ".join(f"{x:+.2f}" for x in b), f"{np.mean(b):+.2f}"])
    md = "\n".join([
        "# M3c addendum: warm-started approximate best responses", "",
        f"Generated by `python -m lanegame experiments-rl br_warm` in {elapsed / 60:.1f} min ({workers} processes). "
        f"Each response starts from a copy of the target's own network and trains {steps:,} PPO steps against the "
        f"frozen target (two training seeds), then is evaluated on {eval_eps} held-out episodes per seat "
        f"(SeedSequence({EVAL_SEED})). Payoff to the response, 95% CI. At the start the response IS the target, so "
        "its payoff is 0 up to noise: any positive value is exploitation found by the response.", "",
        md_table(["target", "warm-started response (per training seed)", "best warm", "best from scratch (m3c)",
                  "lower bound on exploitability"], rows), "",
        "By family (best warm-started response per target seed):", "",
        md_table(["family", "per seed", "mean"], fam), ""])
    write("m3c_br_warm", {"results": {f"{k[0]}|{k[1]}": v for k, v in res.items()}, "summary": summary,
                          "elapsed_s": elapsed, "steps": steps}, md)
    return summary


if __name__ == "__main__":
    run()
